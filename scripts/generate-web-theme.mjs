#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { designMetrics, designTokens } from "../apps/web/src/ui/design.tokens.ts";

const target = new URL("../apps/web/src/ui/theme.css", import.meta.url);
const aliases = {
  canvas: ["--bg"],
  surface: ["--card"],
  elevated: ["--surface-elevated"],
  recessed: ["--surface-recessed"],
  tint: ["--surface-tint"],
  hover: ["--surface-hover"],
  foreground: ["--fg"],
  secondary: ["--fg-2"],
  muted: ["--muted-fg"],
  border: ["--border"],
  controlBorder: ["--border-strong"],
  action: ["--brand", "--opentag-button-primary-bg"],
  actionText: ["--brand-ink"],
  actionHover: ["--opentag-button-primary-hover"],
  actionPressed: ["--opentag-button-primary-pressed"],
  selected: ["--brand-soft"],
  inverse: ["--on-dark"],
  danger: ["--opentag-button-danger-bg"],
  dangerHover: ["--opentag-button-danger-hover"],
};
const semantic = {
  "--color-kumo-canvas": "--bg",
  "--color-kumo-base": "--card",
  "--color-kumo-elevated": "--surface-elevated",
  "--color-kumo-recessed": "--surface-recessed",
  "--color-kumo-tint": "--surface-tint",
  "--color-kumo-overlay": "--card",
  "--color-kumo-control": "--card",
  "--color-kumo-contrast": "--fg",
  "--color-kumo-fill": "--border",
  "--color-kumo-fill-hover": "--surface-hover",
  "--color-kumo-interact": "--border-strong",
  "--color-kumo-line": "--border",
  "--color-kumo-hairline": "--border",
  "--color-kumo-focus": "--brand-ink",
  "--color-kumo-brand": "--brand",
  "--color-kumo-brand-hover": "--opentag-button-primary-hover",
  "--text-color-kumo-default": "--fg",
  "--text-color-kumo-strong": "--fg",
  "--text-color-kumo-subtle": "--fg-2",
  "--text-color-kumo-inactive": "--muted-fg",
  "--text-color-kumo-placeholder": "--muted-fg",
  "--text-color-kumo-inverse": "--on-dark",
  "--text-color-kumo-brand": "--brand-ink",
  "--text-color-kumo-link": "--brand-ink",
};
const metricNames = {
  font: "--ui-font",
  controlRadius: "--ui-control-radius",
  surfaceRadius: "--ui-surface-radius",
  dialogRadius: "--ui-dialog-radius",
  controlHeight: "--ui-control-height",
  compactControlHeight: "--ui-control-height-compact",
  pageTitle: "--ui-page-title",
  compactPageTitle: "--ui-page-title-compact",
  sectionTitle: "--ui-section-title",
  frameWidth: "--ui-frame-width",
  navigationWidth: "--ui-navigation-width",
  railWidth: "--ui-rail-width",
};

function palette(mode) {
  return Object.entries(aliases).flatMap(([name, variables]) =>
    variables.map((variable) => "  " + variable + ": " + designTokens[mode][name] + ";"),
  );
}

const css = [
  "/* Generated by scripts/generate-web-theme.mjs from design.tokens.ts. Run pnpm theme:generate. */",
  ':root[data-opentag-theme="opentag"],',
  '[data-opentag-theme="opentag"] {',
  ...palette("light"),
  ...Object.entries(designMetrics).map(([name, value]) => "  " + metricNames[name] + ": " + value + ";"),
  ...Object.entries(semantic).map(([name, value]) => "  " + name + ": var(" + value + ");"),
  "}",
  "",
  ':root[data-opentag-theme="opentag"][data-opentag-mode="dark"],',
  '[data-opentag-theme="opentag"][data-opentag-mode="dark"],',
  '[data-opentag-theme="opentag"] [data-opentag-mode="dark"] {',
  ...palette("dark"),
  "}",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  if (current !== css) throw new Error("OpenTag theme is out of date. Run pnpm theme:generate.");
  console.log("[web-theme] generated stylesheet is current");
} else {
  await writeFile(target, css);
  console.log("[web-theme] wrote " + fileURLToPath(target));
}
