#!/usr/bin/env node
/*
 * Asserts the built stylesheet against the artifact, not against the wiring that produces it.
 *
 * Both halves of the scan are probed, because they fail independently. A build that scans Kumo's dist
 * but not the application still styles every control while leaving the pages' own classes missing, and
 * the reverse leaves controls with no size or padding. `@tailwindcss/vite` also contributes sources
 * from Vite's module graph, so a broken Kumo `@source` degrades rather than disappears -- 984
 * selectors against 1741 when it is right -- which is precisely why the probes are named classes
 * rather than a size threshold.
 *
 * This file lives outside `apps/web` on purpose. Tailwind's automatic source detection scans the Vite
 * root, so probe names written inside it would be generated by the very build being checked, and the
 * check would pass by describing itself.
 *
 * Two ways of getting this wrong have already shipped: a fixed stylesheet that silently lacked the
 * classes the pages used, and an `@source` that pointed at a path which matched nothing, so Kumo's
 * own component utilities were never generated and every control lost its size and padding. Both
 * built cleanly, type-checked cleanly, and passed the suite. Only the output tells the truth.
 */
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const assets = resolve(dirname(fileURLToPath(import.meta.url)), "..", "apps", "web", "dist", "assets");
const stylesheets = readdirSync(assets).filter((entry) => entry.endsWith(".css"));
if (stylesheets.length === 0) throw new Error(`No stylesheet was emitted into ${assets}`);
const css = stylesheets.map((entry) => readFileSync(join(assets, entry), "utf8")).join("\n");

/** A class is present only when it terminates at a real selector boundary: `.size-8` is not `.size-8\.5`. */
function defines(utility) {
  const escaped = utility.replaceAll(/[.:]/g, (character) => `\\\\${character}`);
  return new RegExp(`\\.${escaped}[,{:\\s\\[>~+]`).test(css);
}

/*
 * The Kumo probes are classes its components render but nothing in OpenTag writes, so each is present
 * only when Kumo's dist is scanned. Any such class works; these were taken from the set difference
 * between a build that scans the dist and one that does not.
 */
const required = [
  { reason: "Kumo control sizing", utility: "h-11" },
  { reason: "Kumo badge palette", utility: "bg-kumo-badge-blue" },
  { reason: "Kumo surface token", utility: "bg-kumo-elevated" },
  { reason: "Kumo spacing scale", utility: "gap-2.5" },
  /*
   * The application probes have to be absent from Kumo's dist as well as present in `apps/web/src`.
   * A class both sides write proves nothing: if application scanning stopped and the dist scan kept
   * working, the class would still be generated and the check would pass over a page with no styles.
   */
  { reason: "OpenTag settings row divider", utility: "last:border-b-0" },
  { reason: "OpenTag shell padding", utility: "md:px-8" },
  { reason: "OpenTag form column split", utility: "sm:grid-cols-2" },
];

const missing = required.filter((entry) => !defines(entry.utility));
if (missing.length > 0) {
  const detail = missing.map((entry) => `  .${entry.utility} (${entry.reason})`).join("\n");
  throw new Error(
    `The built stylesheet is missing utilities the application renders with:\n${detail}\n\n` +
      "Tailwind generates utilities from the sources listed by @source in src/app.css. A source that " +
      "matches nothing fails silently, so this check reads the emitted CSS instead.",
  );
}
console.log(`Verified ${required.length} generated utilities across ${stylesheets.length} stylesheet(s).`);
